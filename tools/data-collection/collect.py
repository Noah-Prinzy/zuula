#!/usr/bin/env python3
"""Collects Uganda-relevant, human-verified fact-checks from AFP Fact Check Africa via
Google's Fact Check Tools API (https://developers.google.com/fact-check/tools/api), in the
exact schema data/fact-checks/seed/*.json and data/fact-checks/eval/*.json already use. See
README.md in this directory for why AFP-only and the known true/false imbalance.

Needs GOOGLE_FACTCHECK_API_KEY. Stdlib only (urllib), no new project dependency.
"""

from __future__ import annotations

import argparse
import json
import logging
import os
import re
import sys
import time
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

logging.basicConfig(level=logging.INFO, format="%(levelname)s: %(message)s")
logger = logging.getLogger("collect")

REPO_ROOT = Path(__file__).resolve().parents[2]
SEED_FILE = REPO_ROOT / "data" / "fact-checks" / "seed" / "afp-fact-check-uganda.json"
EVAL_DIR = REPO_ROOT / "data" / "fact-checks" / "eval"
CACHE_DIR = Path(__file__).resolve().parent / "cache"

API_URL = "https://factchecktools.googleapis.com/v1alpha1/claims:search"
PUBLISHER_SITE = "factcheck.afp.com"
PAGE_SIZE = 50
REQUEST_DELAY_SECONDS = 1.0  # polite pacing; the API has no documented per-second limit

# Broad recall net: the API is keyword search over claim text/claimant, not a country filter,
# so results are filtered post-hoc by _looks_like_uganda() below. Debunk-leaning terms by
# default; --include-true adds a second pass aimed at confirmed-true pieces.
DEBUNK_QUERIES = [
    "Uganda", "Kampala", "Museveni", "Uganda election", "Uganda army", "Uganda police",
    "Uganda government", "Uganda health", "Uganda COVID", "Uganda vaccine", "Uganda economy",
    "Uganda shilling", "Bobi Wine", "Besigye", "NRM Uganda", "NUP Uganda", "Entebbe",
    "Uganda school", "Uganda fuel", "Uganda road", "Uganda minister", "Uganda parliament",
]
TRUE_QUERIES = [
    "Uganda confirms", "Uganda government announces", "Uganda true", "Uganda verified",
    "Uganda ministry of health confirms", "Uganda correct",
]

_UGANDA_WORDS = re.compile(
    r"\buganda|kampala|museveni|ugandan|kyagulanyi|nrm\b|nup\b|entebbe|jinja|gulu|mbarara",
    re.IGNORECASE,
)

# Textual ratings seen across fact-checking publishers' ClaimReview markup, lowercased,
# matched by substring (see _infer_verdict). Extend this when a run logs an unmapped rating —
# never guess silently; an unmapped record is skipped and logged instead.
RATING_MAP: dict[str, str] = {
    # false
    "false": "false",
    "fake": "false",
    "fabricated": "false",
    "hoax": "false",
    "altered photo": "false",
    "altered image": "false",
    "altered video": "false",
    "doctored": "false",
    "miscaptioned": "false",
    "no evidence": "false",
    "pants on fire": "false",
    "scam": "false",
    "incorrect": "false",
    # likely-false / misleading / partly true
    "misleading": "likely-false",
    "partly false": "likely-false",
    "partly true": "likely-false",
    "partially false": "likely-false",
    "partially true": "likely-false",
    "out of context": "likely-false",
    "exaggerated": "likely-false",
    "unproven": "likely-false",
    "unsupported": "likely-false",
    "mostly false": "likely-false",
    "half true": "likely-false",
    "mixed": "likely-false",
    # ai-generated
    "ai-generated": "ai-generated",
    "ai generated": "ai-generated",
    "generated by artificial intelligence": "ai-generated",
    "deepfake": "ai-generated",
    "synthetic media": "ai-generated",
    # authentic / true (checked last so "mostly false" etc. above don't fall through to "true")
    "mostly true": "authentic",
    "true": "authentic",
    "correct": "authentic",
    "accurate": "authentic",
    "verified": "authentic",
    "confirmed": "authentic",
    "real": "authentic",
    "authentic": "authentic",
}
# Longest keys first so "mostly false" matches before the bare "false" substring would.
_RATING_KEYS_BY_LENGTH = sorted(RATING_MAP, key=len, reverse=True)

CATEGORY_KEYWORDS: dict[str, list[str]] = {
    "Elections": ["election", "vote", "ballot", "polling", "electoral commission", "nrm", "nup", "candidate"],
    "Health": ["health", "vaccine", "covid", "ebola", "cholera", "disease", "hospital", "ministry of health", "malaria"],
    "Politics": ["museveni", "president", "parliament", " mp ", "minister", "government", "opposition", "kyagulanyi", "besigye"],
    "Economy": ["economy", "shilling", "tax", "fuel", "price", "inflation", "trade", "bank", "loan", "budget"],
    "Education": ["school", "university", "student", "exam", "education", "teacher"],
    "Weather": ["weather", "flood", "drought", "rain", "climate", "landslide"],
}
DEFAULT_CATEGORY = "Society"


def _infer_category(text: str) -> str:
    low = text.lower()
    for category, keywords in CATEGORY_KEYWORDS.items():
        if any(k in low for k in keywords):
            return category
    return DEFAULT_CATEGORY


def _infer_verdict(rating_text: str) -> str | None:
    low = f" {rating_text.strip().lower()} "
    for key in _RATING_KEYS_BY_LENGTH:
        if key in low:
            return RATING_MAP[key]
    return None


def _looks_like_uganda(claim_text: str, review_title: str, review_url: str) -> bool:
    haystack = f"{claim_text} {review_title} {review_url}"
    return bool(_UGANDA_WORDS.search(haystack))


def _content_type(text: str) -> str:
    low = text.lower()
    if any(w in low for w in ("video", "footage", "clip", "filmed")):
        return "video"
    if any(w in low for w in ("photo", "image", "picture")):
        return "image"
    return "text"


def _fetch_page(api_key: str, query: str, page_token: str | None) -> dict:
    params = {
        "query": query,
        "languageCode": "en",
        "reviewPublisherSiteFilter": PUBLISHER_SITE,
        "pageSize": str(PAGE_SIZE),
        "key": api_key,
    }
    if page_token:
        params["pageToken"] = page_token
    url = f"{API_URL}?{urllib.parse.urlencode(params)}"
    try:
        with urllib.request.urlopen(url, timeout=20) as response:
            return json.loads(response.read())
    except urllib.error.HTTPError as exc:
        body = exc.read().decode("utf-8", errors="replace")
        logger.error("Query %r failed: HTTP %d: %s", query, exc.code, body[:500])
        return {}
    except urllib.error.URLError as exc:
        logger.error("Query %r failed: %s", query, exc)
        return {}


def _cache_path(query: str) -> Path:
    safe = re.sub(r"[^a-z0-9]+", "-", query.lower()).strip("-")
    return CACHE_DIR / f"{safe}.json"


def _collect_for_query(api_key: str, query: str, use_cache: bool) -> list[dict]:
    cache_path = _cache_path(query)
    if use_cache and cache_path.exists():
        logger.info("Using cached results for %r (%s)", query, cache_path.name)
        return json.loads(cache_path.read_text())["claims"]

    claims: list[dict] = []
    page_token = None
    while True:
        page = _fetch_page(api_key, query, page_token)
        page_claims = page.get("claims") or []
        claims.extend(page_claims)
        page_token = page.get("nextPageToken")
        if not page_token:
            break
        time.sleep(REQUEST_DELAY_SECONDS)

    CACHE_DIR.mkdir(parents=True, exist_ok=True)
    cache_path.write_text(json.dumps({"query": query, "claims": claims}, indent=2))
    logger.info("Query %r: %d raw claims (cached to %s)", query, len(claims), cache_path.name)
    return claims


def _existing_source_urls() -> set[str]:
    urls: set[str] = set()
    for path in [SEED_FILE, *EVAL_DIR.glob("*.json")]:
        if path.exists():
            urls.update(r["source_url"] for r in json.loads(path.read_text()))
    return urls


def _to_record(claim: dict, review: dict) -> dict | None:
    claim_text = (claim.get("text") or "").strip()
    review_title = (review.get("title") or "").strip()
    review_url = review.get("url") or ""
    if not claim_text or not review_url:
        return None
    if not _looks_like_uganda(claim_text, review_title, review_url):
        return None

    rating_text = review.get("textualRating") or ""
    verdict = _infer_verdict(rating_text)
    if verdict is None:
        logger.warning("Unmapped rating %r for %s — skipped", rating_text, review_url)
        return None

    published = (review.get("reviewDate") or claim.get("claimDate") or "")[:10]
    if not published:
        logger.warning("No date for %s — skipped", review_url)
        return None

    return {
        "source_org": (review.get("publisher") or {}).get("name") or "AFP Fact Check",
        "source_url": review_url,
        "claim": claim_text,
        "verdict": verdict,
        "summary": review_title or claim_text,
        "citations": [{"title": review_title or claim_text, "url": review_url}],
        "published_at": published,
        "language": "English",
        "category": _infer_category(f"{claim_text} {review_title}"),
        "country": "UG",
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--include-true", action="store_true", help="Also run TRUE_QUERIES")
    parser.add_argument("--dry-run", action="store_true", help="Collect and report, write nothing")
    parser.add_argument("--limit", type=int, default=None, help="Cap new records kept after dedup")
    parser.add_argument("--no-cache", action="store_true", help="Ignore tools/data-collection/cache/")
    args = parser.parse_args()

    api_key = os.environ.get("GOOGLE_FACTCHECK_API_KEY", "").strip()
    if not api_key:
        logger.error("GOOGLE_FACTCHECK_API_KEY is not set. See README.md.")
        return 1

    queries = list(DEBUNK_QUERIES)
    if args.include_true:
        queries += TRUE_QUERIES

    existing_urls = _existing_source_urls()
    logger.info("%d source_urls already in seed/ + eval/ (dedup against these)", len(existing_urls))

    seen_urls: set[str] = set()
    new_records: list[dict] = []
    for query in queries:
        raw_claims = _collect_for_query(api_key, query, use_cache=not args.no_cache)
        for claim in raw_claims:
            for review in claim.get("claimReview") or []:
                record = _to_record(claim, review)
                if record is None:
                    continue
                url = record["source_url"]
                if url in existing_urls or url in seen_urls:
                    continue
                seen_urls.add(url)
                new_records.append(record)
        if not args.no_cache and _cache_path(query).exists():
            continue  # was served from cache; no need to pace
        time.sleep(REQUEST_DELAY_SECONDS)

    if args.limit:
        new_records = new_records[: args.limit]

    verdict_counts: dict[str, int] = {}
    for r in new_records:
        verdict_counts[r["verdict"]] = verdict_counts.get(r["verdict"], 0) + 1
    logger.info("Collected %d new, deduped Uganda records: %s", len(new_records), verdict_counts)

    if args.dry_run:
        logger.info("--dry-run: nothing written.")
        return 0

    if not new_records:
        logger.info("Nothing new to write.")
        return 0

    existing = json.loads(SEED_FILE.read_text()) if SEED_FILE.exists() else []
    merged = existing + new_records
    merged.sort(key=lambda r: (r["country"], r["source_url"]))
    SEED_FILE.write_text(json.dumps(merged, indent=2, ensure_ascii=False) + "\n")
    logger.info("Wrote %d total records to %s (%d new)", len(merged), SEED_FILE, len(new_records))
    return 0


if __name__ == "__main__":
    sys.exit(main())
